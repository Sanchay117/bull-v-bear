// Copies the CourtRecord ABI from the Foundry build into core/src/abi.ts.
// Usage: (cd contracts && forge build) && node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(readFileSync(join(root, "contracts/out/CourtRecord.sol/CourtRecord.json"), "utf8"));

const header = "// Generated by scripts/gen-abi.mjs from contracts/out — do not edit by hand.\n";
writeFileSync(
  join(root, "core/src/abi.ts"),
  `${header}export const courtRecordAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
// Kept out of the package index so the CRE workflow bundle never carries it.
writeFileSync(
  join(root, "core/src/bytecode.ts"),
  `${header}export const courtRecordBytecode = ${JSON.stringify(artifact.bytecode.object)} as const;\n`,
);
console.log(`Wrote core/src/abi.ts (${artifact.abi.length} ABI entries) and core/src/bytecode.ts`);
